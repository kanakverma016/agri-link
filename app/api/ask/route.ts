const buildPrompt = (question: string, lang: AskLang) => {
  const spec = LANG_SPEC[lang]
  return `
You are 'SmartKrishi,' an expert agricultural advisor.
Your response MUST be in ${spec.language}. Use language a kisan (farmer) can easily understand.
FIRST, check if the user's question (and image, if provided) is related to farming (crops, soil, pests, diseases, fertilizer). The question may be written in any language; always answer in the language specified above.
IF IT IS NOT a farming question, you MUST respond ONLY with this exact text:
"${spec.refusal}"
IF IT IS a farming question, you MUST provide your answer using this EXACT format.
DO NOT use markdown like '**' or '*'.
Use plain text headings. Put an empty line (a gap) after each heading.
For lists, use numbers like 1., 2., 3.

${spec.problem}
(Explain the problem simply.)

${spec.solution}
(Provide numbered steps. e.g., "1. [Step 1]")
(e.g., "2. [Step 2]")

${spec.prevention}
(Provide 2-3 numbered steps for prevention.)

${spec.disclaimer}
${spec.disclaimerText}

FINALLY, on a new last line, honestly rate how confident you are that your advice is correct and safe for this exact situation, as a whole number from 0 to 100. Write it as: CONFIDENCE: <number>
Use a LOW number (below 50) when the question is vague, the image is unclear, the diagnosis needs lab or field inspection, or several causes are possible. Use 75 or above only when the problem and fix are clear.
This CONFIDENCE line is required for every farming answer (never for the refusal text), always in English letters, with no other text after it.
---
Here is the farmer's question:
"${question}"
`
}

export async function POST(request: Request) {
  if (!(await verifyUser(request))) return jsonError('Unauthorized', 401)

  const body = (await request.json().catch(() => null)) as Record<string, unknown> | null
  const questionText = typeof body?.question === 'string' ? body.question.trim() : ''
  const imageBase64 = typeof body?.imageBase64 === 'string' ? body.imageBase64 : ''
  const imageMimeType = typeof body?.imageMimeType === 'string' ? body.imageMimeType : ''
  const lang: AskLang = body?.lang === 'hi' || body?.lang === 'mr' ? body.lang : 'en'

  if (!questionText && !imageBase64) return jsonError('Please type a question or upload an image.', 400)
  if (questionText.length > MAX_QUESTION_CHARS) {
    return jsonError(`Question must be ${MAX_QUESTION_CHARS} characters or fewer.`, 400)
  }
  if (imageBase64) {
    if (imageBase64.length > MAX_IMAGE_BASE64_CHARS) return jsonError('Image is too large (max 5 MB).', 413)
    if (!IMAGE_TYPES.includes(imageMimeType)) return jsonError('Unsupported image type.', 400)
  }

  const parts: Record<string, unknown>[] = [
    { text: buildPrompt(questionText || 'Please identify the problem in this image.', lang) },
  ]
  if (imageBase64) parts.push({ inlineData: { mimeType: imageMimeType, data: imageBase64 } })

  try {
    const { text } = await generateWithSarvamFallback({ contents: [{ parts }] }, 1)
    const { answer, confidence } = extractModelConfidence(text)
    return Response.json({ answer, confidence })
  } catch (err) {
    if (err instanceof GeminiError) return jsonError(err.message, err.status)
    return jsonError('Failed to get an answer.', 500)
  }
}
